class TestWebhooks:
    def test_accepts_own_signature(self):
        m = make()
        body = json.dumps({"event": "invoice.settled"})
        assert m.verify_webhook(body, m.sign_webhook(body))

    def test_rejects_tampered_body(self):
        m = make()
        sig = m.sign_webhook(json.dumps({"amount": 100}))
        assert not m.verify_webhook(json.dumps({"amount": 999}), sig)

    def test_rejects_other_secret(self):
        a = make()
        b = make(webhook_secret="a-completely-different-secret")
        body = '{"x":1}'
        assert not a.verify_webhook(body, b.sign_webhook(body))

    def test_rejects_junk_signatures(self):
        m = make()
        for bad in ("", "sha256=", "not-hex", "sha256=zz"):
            assert not m.verify_webhook("{}", bad)

    def test_raises_without_secret(self):
        m = make(webhook_secret=None)
        with pytest.raises(MaskError):
            m.verify_webhook("{}", "sha256=00")

    def test_signature_format_matches_node_sdk(self):
        m = make()
        sig = m.sign_webhook('{"a":1}')
        assert sig.startswith("sha256=")
        assert len(sig) == len("sha256=") + 64
